-- Cache auth.uid() once per statement and scope browser policies explicitly to
-- authenticated users.
drop policy if exists "Profiles are self-readable" on public.profiles;
create policy "Profiles are self-readable" on public.profiles for select to authenticated using (id = (select auth.uid()));
drop policy if exists "Profiles are self-updatable" on public.profiles;
create policy "Profiles are self-updatable" on public.profiles for update to authenticated using (id = (select auth.uid())) with check (id = (select auth.uid()));
drop policy if exists "Users can insert own profile" on public.profiles;
create policy "Users can insert own profile" on public.profiles for insert to authenticated with check (id = (select auth.uid()));

drop policy if exists "Members can read events" on public.events;
create policy "Members can read events" on public.events for select to authenticated using (owner_id = (select auth.uid()) or private.is_event_member(id));
drop policy if exists "Authenticated users can create events" on public.events;
create policy "Authenticated users can create events" on public.events for insert to authenticated with check (owner_id = (select auth.uid()));
drop policy if exists "Owners can update events" on public.events;
create policy "Owners can update events" on public.events for update to authenticated using (owner_id = (select auth.uid())) with check (owner_id = (select auth.uid()));

