-- Add covering indexes for every current single/multi-column foreign key that
-- lacks one. Names derive from stable constraint names and remain idempotent.
do $$
declare row record;
begin
  for row in
    select n.nspname schema_name, c.relname table_name, con.conname constraint_name,
      array_agg(a.attname order by k.ordinality) column_names
    from pg_constraint con
    join pg_class c on c.oid = con.conrelid
    join pg_namespace n on n.oid = c.relnamespace
    join unnest(con.conkey) with ordinality k(attnum, ordinality) on true
    join pg_attribute a on a.attrelid = c.oid and a.attnum = k.attnum
    where con.contype = 'f' and n.nspname = 'public'
      and not exists (
        select 1 from pg_index i
        where i.indrelid = c.oid
          and (i.indkey::smallint[])[0:cardinality(con.conkey)-1] = con.conkey
      )
    group by n.nspname, c.relname, con.conname
  loop
    execute format('create index if not exists %I on %I.%I (%s)',
      left(row.constraint_name || '_idx', 63), row.schema_name, row.table_name,
      (select string_agg(format('%I', value), ', ') from unnest(row.column_names) value));
  end loop;
end $$;
